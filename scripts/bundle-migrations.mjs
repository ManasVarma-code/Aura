import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = new URL('../supabase/', import.meta.url);
const directory = new URL('migrations/', root);
const files = (await readdir(directory)).filter(name => /^\d+_.+\.sql$/.test(name)).sort();
if (!files.length) throw new Error('No Aura migrations found.');
const versions = files.map(name => name.split('_')[0]);
const tables = ['profiles','couples','couple_members','messages','calendar_events','memories','mood_checkins','cycle_settings'];
const quote = value => "'"+value.replaceAll("'","''")+"'";
let sql = `-- Generated by npm run db:bundle. Run in the intended Supabase project's SQL Editor.
-- Initial Aura installation only. Existing Aura tables or a private schema abort safely.
-- No credentials are embedded. All migrations and their history commit together.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '120s';
SELECT pg_advisory_xact_lock(hashtext('Aura:initial-schema'));
DO $aura_preflight$
DECLARE item text;
BEGIN
  IF to_regclass('auth.users') IS NULL OR to_regclass('storage.objects') IS NULL OR to_regclass('storage.buckets') IS NULL THEN
    RAISE EXCEPTION 'This installer requires a Supabase project with Auth and Storage schemas.';
  END IF;
  FOREACH item IN ARRAY ARRAY[${tables.map(quote).join(',')}] LOOP
    IF to_regclass('public.' || item) IS NOT NULL THEN
      RAISE EXCEPTION 'Existing public.% found. Stop and inspect the project before applying Aura migrations.', item;
    END IF;
  END LOOP;
  IF to_regnamespace('private') IS NOT NULL THEN
    RAISE EXCEPTION 'An existing private schema was found. Inspect it before installing Aura; this installer will not alter it.';
  END IF;
  IF EXISTS (SELECT 1 FROM pg_extension e JOIN pg_namespace n ON n.oid=e.extnamespace WHERE e.extname='pgcrypto' AND n.nspname<>'extensions') THEN
    RAISE EXCEPTION 'pgcrypto must be installed in extensions; review the existing extension location first.';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_publication WHERE pubname='supabase_realtime') THEN
    RAISE EXCEPTION 'The supabase_realtime publication is missing. Enable/configure Realtime first.';
  END IF;
END;
$aura_preflight$;
CREATE SCHEMA IF NOT EXISTS supabase_migrations;
CREATE TABLE IF NOT EXISTS supabase_migrations.schema_migrations (
  version text PRIMARY KEY,
  statements text[],
  name text
);
DO $aura_history$
BEGIN
  IF (SELECT count(*) FROM information_schema.columns WHERE table_schema='supabase_migrations' AND table_name='schema_migrations' AND column_name IN ('version','statements','name')) <> 3 THEN
    RAISE EXCEPTION 'Unexpected migration history structure. Use the Supabase CLI after reviewing the project.';
  END IF;
  IF EXISTS (SELECT 1 FROM supabase_migrations.schema_migrations WHERE version IN (${versions.map(quote).join(',')})) THEN
    RAISE EXCEPTION 'Aura migration history already exists. Inspect the project instead of reinstalling.';
  END IF;
END;
$aura_history$;
`;
for (const file of files) {
  const source = await readFile(new URL(file, directory),'utf8');
  const version = file.split('_')[0];
  const name = file.slice(version.length+1,-4);
  const tag = `$aura_migration_${version}$`;
  if (source.includes(tag)) throw new Error('Migration contains its history delimiter.');
  sql += `\n-- Migration: ${file}\n${source}\nINSERT INTO supabase_migrations.schema_migrations(version,name,statements) VALUES (${quote(version)},${quote(name)},ARRAY[${tag}${source}${tag}]);\n`;
}
sql += "\nNOTIFY pgrst, 'reload schema';\nCOMMIT;\n";
const destination = new URL('install-aura.sql',root);
await writeFile(destination,sql);
console.log(`Created ${fileURLToPath(destination)} from ${files.length} migrations. No database was modified.`);
